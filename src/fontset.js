/**
 * fontset.js — the built-in hexadecimal font.
 *
 * CHIP-8 programs can draw the digits 0-F using the FX29 instruction.
 * Each digit is a sprite that is 8 pixels wide (we only use the top 4 bits)
 * and 5 rows tall, so each digit takes 5 bytes. 16 digits * 5 bytes = 80 bytes.
 *
 * Example, the digit "0":
 *   0xF0 = 1111 ....   ####
 *   0x90 = 1001 ....   #  #
 *   0x90 = 1001 ....   #  #
 *   0x90 = 1001 ....   #  #
 *   0xF0 = 1111 ....   ####
 */

/** Where the font lives in memory. 0x050 is the most common convention. */
export const FONT_START = 0x050;

/** Height of every font sprite in rows (= bytes). */
export const FONT_CHAR_SIZE = 5;

export const FONT = new Uint8Array([
  0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
  0x20, 0x60, 0x20, 0x20, 0x70, // 1
  0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
  0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
  0x90, 0x90, 0xF0, 0x10, 0x10, // 4
  0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
  0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
  0xF0, 0x10, 0x20, 0x40, 0x40, // 7
  0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
  0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
  0xF0, 0x90, 0xF0, 0x90, 0x90, // A
  0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
  0xF0, 0x80, 0x80, 0x80, 0xF0, // C
  0xE0, 0x90, 0x90, 0x90, 0xE0, // D
  0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
  0xF0, 0x80, 0xF0, 0x80, 0x80, // F
]);
